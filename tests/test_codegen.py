def test_codegen_parse_template_nodes():
    from skelantic.templates.parser import LineNode, Variable, TemplateNode
    
    # Create mock nodes
    var1 = Variable("title", "str")
    line1 = LineNode(variables=[var1])
    var2 = Variable("count", "int")
    line2 = LineNode(variables=[var2])
    
    block_node = TemplateNode("block", "MyBlock", [line2])
    
    nodes = [line1, block_node]
    
    cg = CodeGenerator(".")
    classes_out = {}
    cg._parse_template_nodes(nodes, "MyTemplate", classes_out)
    
    assert "MyTemplate" in classes_out
    assert classes_out["MyTemplate"]["title"] == "str"
    assert classes_out["MyTemplate"]["MyBlock"] == "'MyTemplateMyblockBlock'"
    
    assert "MyTemplateMyblockBlock" in classes_out
    assert classes_out["MyTemplateMyblockBlock"]["count"] == "int"

